export function ScenarioIcon({ id }: { id: string }) {
  const rows = ICONS[id] ?? ICONS.bus;
  const rects: JSX.Element[] = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />);
    }),
  );
  return (
    <svg className="scen-icon" viewBox="0 0 14 10" aria-hidden="true" shapeRendering="crispEdges">
      {rects}
    </svg>
  );
}
